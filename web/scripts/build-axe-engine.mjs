// Bundles the AXE Insights engine (src/features/axeInsights/engine) into a
// single dependency-free CommonJS file for Cloud Functions, so the server
// runs exactly the code the web app is tested with. The output is
// committed; CI rebuilds it and fails if the committed copy is stale.
//
//   npm run build:axe-engine        (from web/)
import { build } from 'rolldown'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const out = fileURLToPath(new URL('../../functions/generated/axeInsightsEngine.js', import.meta.url))
const entry = fileURLToPath(new URL('../src/features/axeInsights/engine/index.ts', import.meta.url))

await build({
  input: entry,
  platform: 'node',
  logLevel: 'warn',
  output: { file: out, format: 'cjs' },
})

const body = await readFile(out, 'utf8')
await writeFile(
  out,
  '// GENERATED by web/scripts/build-axe-engine.mjs from web/src/features/axeInsights/engine.\n' +
    '// Do not edit by hand: change the TypeScript source and run `npm run build:axe-engine` in web/.\n' +
    body,
)
